    print("="*70)
    print("III 型测试：Dirichlet 模板解剖")
    print("="*70)
    
    # Dirichlet 模板：L(1,χ) ≠ 0 的算术证明（非解析——）
    print("\n1. Dirichlet 模板（成功的 III 型——）:")
    print("   局部配置：模 q 的 character χ 的'和'结构")
    print("   排他对象：L(1,χ) = 0（s=1 的零点——）")
    print("   机制：L(1,χ) = (类数 × 正则子 × π)/√q 型——【代数正量】")
    print("        ——类数 ≥ 1（正整数——）⟹ L(1,χ) > 0 ⟹ 无零点在 s=1")
    print("   关键：正性来自【代数】（类数——）——不经零点——")
    
    # 为什么停在 s=1？
    print("\n2. 为什么 Dirichlet 停在 s=1——不能推进到 s=½:")
    print("   s=1 的算术可及性：L(1,χ) = 类数公式（代数对象的值——）")
    print("   ——L 函数在 s=1 的值连接【代数】（类数/正则子——）")
    print("   s=½ 的算术可及性：L(½,χ) 无类数型公式")
    print("   ——s=½ 在带内——不在'算术可及区'（σ>1 的代数区——）")
