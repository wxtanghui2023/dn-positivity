#!/usr/bin/env python3
"""
二次观测攻击——|F|² 类能否不解析 γ 提取 δ？
G(t) = 平滑 ψ 误差的 x^{-1/2} 归一化——显式公式模态叠加
G(t) = Σ_ρ e^{(ρ−1/2)t}/ρ + ...——在线 e^{iγt}/ρ——离轴 e^{δt}e^{iγt}/ρ

二次量：|G(t)|² = Σ_{ρ,ρ'} e^{(δ_ρ+δ_ρ')t}e^{i(γ_ρ−γ_ρ')t}/(ρρ̄')
- 交叉项（ρ≠ρ'——）：振荡（γ差——）——时间平均 → 0
- 对角（ρ=ρ'——）：e^{2δ_ρt}/|ρ|²——在线常数——离轴增长

关键：提取对角需要"分辨"（长时间平均——）吗？
"""
import numpy as np

def main():
    print("="*70)
    print("二次观测分析——对角 vs 交叉")
    print("="*70)
    
    # 模型：G(t) 的模态叠加（数值——少量零点——一个离轴——）
    # 在线零点（前几个 γ——）+ 一个离轴（δ=0.05——某个 γ 高度——）
    gammas_on = np.array([14.13, 21.02, 25.01, 30.42, 32.94, 37.59])
    
    print("\n1. |G(t)|² 的结构:")
    print("   对角（ρ=ρ'——）= Σe^{2δt}/|ρ|²——在线常数——离轴增长 e^{2δt}")
    print("   交叉（ρ≠ρ'——）= e^{i(γ−γ')t}——振荡——平均掉")
    print("   ⟹ |G(t)|² 长时间行为 = 对角 = 检测离轴（e^{2δt}——）")
    print("   ——但需要'长时间'（分辨——）")
    
    # 2. 数值：|G(t)|² 的 t-行为（带一个离轴 vs 全在线——）
    print("\n2. 数值比较——|G(t)|² 的增长:")
    delta = 0.05
    # 模态系数（简化——1/ρ——）
    def G_modes(t, has_offline):
        """G(t) 的模态和（简化——在线几个 + 可选离轴——）"""
        val = 0
        # 在线
        for g in gammas_on:
            rho_abs = np.sqrt(0.25 + g**2)
            val += np.exp(1j*g*t)/rho_abs
        # 离轴（如果——）——放在 γ=100 高度
        if has_offline:
            g_off = 100.0
            rho_abs = np.sqrt(0.55**2 + g_off**2)
            val += np.exp(delta*t)*np.exp(1j*g_off*t)/rho_abs
        return val
    
    print(f"   |G(t)|²——在线 vs 带离轴（δ={delta}@γ=100——）:")
    print(f"   {'t':>6} {'|G|² 在线':>14} {'|G|² 带离轴':>14}")
    for t in [0, 2, 5, 10, 15, 20]:
        Gon = abs(G_modes(t, False))**2
        Goff = abs(G_modes(t, True))**2
        print(f"   {t:>6} {Gon:>14.6f} {Goff:>14.6f}")
    
    # 3. 交叉项的角色
    print("\n3. 关键——交叉项:")
    print("   离轴(γ=100)与在线(γ~14-37)的交叉：e^{δt}e^{i(100−γ)t}——高频振荡——")
    print("   短时间（t<~0.5——）交叉贡献——长时间平均掉——")
    print("   对角离轴 e^{2δt}/100²——在 t~20: e²/10⁴ ~ 7.4e-4——很小（γ=100 分母——）")
    print("   ⟹ 离轴在 |G|² 的检测需要 t ~ 1/(2δ) 且离轴 γ 不太大——")
    
    # 4. 含义
    print("\n4. 分析:")
    print("   ① |G|² 对角提取离轴 e^{2δt}——但需长时间（分辨——）")
    print("   ② 离轴高 γ：对角项 e^{2δt}/γ²——γ 分母仍衰减（1/γ²——）")
    print("   ③ 二次量没有完全摆脱——对角仍含 1/|ρ|²——高离轴弱——")
    print("   ④ 相关函数 F(t+h)F̄(t)——对角 e^{iγh}e^{2δt}——h 扫描可辨 γ（分辨——）")

if __name__ == "__main__":
    main()
