# ---------- C. HNF + index, WITH self-checks ----------
def hnf_index(rows, n=8):
    """returns (index, basis_rows) for the full-rank lattice generated by rows (integers)"""
    M=[list(map(int,r)) for r in rows]
    R=len(M); piv=0
    for c in range(n):
        if piv>=R: break
        while True:
            nz=[i for i in range(piv,R) if M[i][c]!=0]
            if not nz: break
            i0=min(nz,key=lambda i:abs(M[i][c]))
            M[piv],M[i0]=M[i0],M[piv]
            p=M[piv][c]
            for i in range(R):
                if i!=piv and M[i][c]!=0:
                    q=M[i][c]//p
                    if q: M[i]=[M[i][j]-q*M[piv][j] for j in range(n)]
            nz=[i for i in range(piv+1,R) if M[i][c]!=0]
            if not nz: break
            if all(abs(M[i][c])<abs(p) for i in nz): continue
            # otherwise loop to reduce further
        piv+=1
    # collect pivot rows
    nonzero=[r for r in M if any(x!=0 for x in r)]
    if len(nonzero)<n: return None,None
    B=nonzero[:n]
    d=abs(detf([[F(B[i][j]) for j in range(n)] for i in range(n)]))
    return (d if d!=0 else None), B

