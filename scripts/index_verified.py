# ---------- D. round-2 at p=2 with HNF + multiplication closure ----------
def v2frac(x):
    """2-adic valuation of a Fraction"""
    if x==0: return 10**9
    n=x.numerator; d=x.denominator
    k=0
    while n%2==0: n//=2; k+=1
    while d%2==0: d//=2; k-=1
    return k
def normL(v): return detf(mulmat(v))
def vq(v): return v2frac(abs(normL(v)))

