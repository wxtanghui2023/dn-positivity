def mm(A,B):
    n=len(A); return [[sum(A[i][t]*B[t][j] for t in range(n)) for j in range(n)] for i in range(n)]
def detf(M):
    """determinant over Q via Gaussian elimination (O(n^3))"""
    n=len(M)
    A=[[F(x) for x in row] for row in M]
    det=F(1)
    for c in range(n):
        piv=None
        for r in range(c,n):
            if A[r][c]!=0: piv=r; break
        if piv is None: return F(0)
        if piv!=c:
            A[c],A[piv]=A[piv],A[c]; det=-det
        det*=A[c][c]
        inv=A[c][c]
        for r in range(c+1,n):
            if A[r][c]!=0:
                f=A[r][c]/inv
                for j in range(c,n): A[r][j]-=f*A[c][j]
    return det

