# ---------- A. ring arithmetic in L = Q(delta,i):  x = u + v i,  u,v in Z[delta] ----------
def mul4(u,v):
    raw=[0]*7
    for i,a in enumerate(u):
        for j,b in enumerate(v): raw[i+j]+=a*b
    for k in range(6,3,-1):
        c=raw[k]
        if c: raw[k]-=c; raw[k-4]+=2*c
    return tuple(raw[:4])
def add4(u,v): return tuple(a+b for a,b in zip(u,v))
def sub4(u,v): return tuple(a-b for a,b in zip(u,v))
def Lmul(x,y):
    u,v=x; u2,v2=y
    return (sub4(mul4(u,u2),mul4(v,v2)), add4(mul4(u,v2),mul4(v,u2)))
def Ladd(x,y): return (add4(x[0],y[0]), add4(x[1],y[1]))
def Lneg(x): return (tuple(-c for c in x[0]), tuple(-c for c in x[1]))
