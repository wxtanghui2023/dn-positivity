def reduce_to_basis(rows):
    """return an 8x8 basis (Fractions) of the lattice spanned by rows, via integer HNF on cleared denominators"""
    D=1
    for r in rows:
        for x in r: D=D*x.denominator//math.gcd(D,x.denominator)
    ints=[[int(F(x)*D) for x in r] for r in rows]
    idx,B=hnf_index(ints)
    if idx is None: return None,None
    return [[F(x,D) for x in row] for row in B], idx
