# ---------------------------------------------------------------- Test B: the exact affine identity
print("="*86); print("TEST B  the exact relation between the two extension orders"); print("="*86)
def addset(S,a): return frozenset(x+a for x in S)
def mulset(S,m): return frozenset(x*m for x in S)
samples=[frozenset(range(0,30,3)), frozenset([1,5,9,13]), frozenset(x for x in range(-40,40) if x%4==1),
         frozenset(range(0,50))]
