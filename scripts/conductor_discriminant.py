def mul(a,b):
    i,j=a; k,l=b
    # (s^i t^j)(s^k t^l) : move t^j past s^k  ->  t^j s^k = s^{(-1)^j k} t^j
    kk = k if j==0 else (-k)%4
    return ((i+kk)%4, (j+l)%2)
