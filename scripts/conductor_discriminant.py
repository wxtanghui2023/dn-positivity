def gen(sub):   # subgroup generated by a set
    S={(0,0)}; fr=[(0,0)]
    while fr:
        x=fr.pop()
        for g in sub:
            y=mul(x,g)
            if y not in S: S.add(y); fr.append(y)
    return frozenset(S)
