#!/usr/bin/env python3
"""
跨越路径验证 2：D_F 整体表达式（不经零点枚举——）
D_F = Q_F − Q'_RH,F = −Σw_H(γ,δ) + Σq(γ)（q = 1/(1+γ²)²——w_H(γ,0)=q(γ)——）
用整体配对从 ξ_F 算：
−Σw_H(γ,δ) = ⟨S_F, H₀⟩ − ⟨S_reg,F, H₀⟩ 的配对对应
Σq(γ) = Weil 值 W_F(q)（素数侧——）

直接策略：验证两个"可算量"的等式：
D_F = 0 ⟺ −Σm_ρw_H(γ_ρ,δ_ρ)（从零点——） = −W_F(q)（Weil——素数侧——）
对在线零点（δ=0——）：−Σw_H(γ,0) = −Σq(γ) = −W_F(q)——Weil 公式（无条件——）
⟹ 判据 D_F（δ=0 配置——）= 0 ⟺ Weil 公式成立——【对任意在线配置——trivial——】

关键：离轴配置（δ≠0——）的 D_F = Σ[q(γ) − w_H(γ,δ)] > 0——
——需要"从 ξ_F 算"来检测离轴——即——Σw_H(γ,δ)（离轴——）≠ W_F(q)
——而 Σw_H(γ,δ)（含 δ——）从 ξ_F 算——S_F 的配对——δ 在 K^nat_ρ 里——
——K^nat_ρ(t) = (δ²−(t−γ)²)/(δ²+(t−γ)²)²——含 δ——
——S_F(t)（从 ξ_F 数值——）= Σm_ρK^nat_ρ(t) + S_reg——含 δ（通过零点——）
——所以 S_F 的配对 ⟨S_F,H₀⟩ 含 δ 信息——【从 ξ_F 算——不经零点枚举——】
——但——S_F 含 δ 是因为 ξ_F 的零点（δ——）影响 ξ_F 的值——
——ξ_F 的值（沿临界线——）在离轴零点附近【无异常】（离轴零点不在临界线——）
——所以 S_F(t)（沿临界线——）【不含离轴 δ 信息】！——（前面分析——）
——离轴零点 ρ=β+iγ（β≠½）——ξ_F(½+it) 在 t=γ 处 ≠ 0——无跳变——
——S_F(t)（临界线——）只"看到"在线零点（δ=0——）——

⚠️ 结论：从 ξ_F 沿【临界线】算——看不到离轴零点——需要【离开临界线】
"""
import numpy as np

def main():
    print("="*70)
    print("关键认识：临界线数据 vs 离轴零点")
    print("="*70)
    
    # 演示：离轴零点对临界线数据的影响
    # ξ(s) 的零点在 ρ=β+iγ（离轴——）——沿临界线 t 扫——在 t=γ 处
    # ξ(½+iγ) ≠ 0（因为零点在 β+iγ 不在 ½+iγ——）——无跳变——
    # vs 在线零点（β=½——）——ξ(½+iγ)=0——跳变——
    print("\n1. 离轴零点 ρ=0.6+30i（人工——）对临界线的影响:")
    # log|ξ(½+it)| 的贡献 ~ log|1−(½+it)/ρ|（Hadamard——）
    # 在 t 接近 γ=30 时——|1−(½+it)/(0.6+30i)|——
    for t in [28, 29, 29.5, 30, 30.5, 31, 32]:
        # 单个零点的贡献到 log|ξ(½+it)|：log|1−(½+it)/ρ|
        rho = 0.6 + 30j
        contrib = np.log(abs(1 - (0.5+1j*t)/rho))
        # 在线零点对比（β=0.5——）
        rho_on = 0.5 + 30j
        contrib_on = np.log(abs(1 - (0.5+1j*t)/rho_on))
        print(f"   t={t}: 离轴贡献={contrib:+.4f}——在线贡献={contrib_on:+.4f}")
    
    print("\n   ——离轴零点：贡献在 t=30 附近【平滑变化】（无跳变——）")
    print("   ——在线零点：贡献在 t=30 处【发散】（log|t−γ|——跳变——）")
    print("   ——临界线的 S_F(t) 只看到在线零点——离轴零点不可见——")
    
    print("\n2. 所以——从 ξ_F 沿临界线算——看不到离轴 δ——")
    print("   要看到离轴——必须【离开临界线】（σ≠½——在 σ=β 处——）")
    print("   ——但 β 未知（要找的——）——这是'跨越'的精确困难——")
    print("   ——除非——用【σ 扫描】的完整数据（ζ 在 σ>½ 的值——）——")
    print("   ——RH 给 ζ 在 σ>½ 无零点（——）——ζ 在 σ>½ 的结构——")
    print("   ——χ 加权的 L(s,χ) 在 σ>½——离轴零点（若有——）会显现——")

if __name__ == "__main__":
    main()
